"""
Records a dataset. Actions for the robot can be either generated by teleoperation or by a policy.
This version injects default CLI args when run without arguments and randomizes the MuJoCo cube
position uniformly in:
  x in [0.18, 0.30], y in [-0.15, 0.15], z = 0.015 (on plane)
BEFORE each episode begins (including the first), without modifying the robot class.
It also enforces that the sampled cube position is at least 5 cm away from the end-goal
point (0.2, -0.15, 0.005) in the XY plane.
"""

